#include "s2html_conv.h"
#include "s2html_event.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int write_html_header(FILE *out, const char *title)
{
    return fprintf(out,
        "<!doctype html>\n<html lang=\"en\">\n<head>\n"
        "  <meta charset=\"utf-8\">\n"
        "  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n"
        "  <title>%s — Source to HTML</title>\n"
        "  <link rel=\"stylesheet\" href=\"styles.css\">\n"
        "</head>\n<body>\n"
        "  <header><h1>Source to HTML</h1><p>Syntax-highlighted C source</p></header>\n"
        "  <main><pre class=\"source\"><code>\n", title) < 0 ? -1 : 0;
}

int s2html_convert_file(const char *input_path, const char *output_path)
{
    FILE *in = NULL, *out = NULL;
    int ch, line = 1, result = 0;
    char *title;
    size_t title_len;

    in = fopen(input_path, "rb");
    if (!in) {
        perror(input_path);
        return -1;
    }
    out = fopen(output_path, "wb");
    if (!out) {
        perror(output_path);
        fclose(in);
        return -1;
    }

    title_len = strlen(input_path);
    title = (char *)malloc(title_len + 1);
    if (!title) {
        fprintf(stderr, "Out of memory.\n");
        fclose(in); fclose(out);
        return -1;
    }
    memcpy(title, input_path, title_len + 1);

    if (write_html_header(out, title) != 0) result = -1;
    free(title);

    while (result == 0 && (ch = fgetc(in)) != EOF) {
        S2Event event;
        if (s2_next_event(in, ch, line, &event) != 0) {
            result = -1;
            break;
        }
        if (s2_write_event(out, &event) != 0) {
            result = -1;
            break;
        }
        line = event.next_line;
    }

    if (result == 0 && fprintf(out,
        "\n</code></pre></main>\n"
        "<footer>Generated by Source-to-HTML (C teaching project)</footer>\n"
        "</body>\n</html>\n") < 0) result = -1;

    if (ferror(in)) result = -1;
    if (fclose(in) != 0) result = -1;
    if (fclose(out) != 0) result = -1;
    return result;
}
